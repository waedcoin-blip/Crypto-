import assert from 'node:assert/strict';
import fs from 'node:fs';
const routing = fs.readFileSync('src/services/rpcRouting.ts','utf8');
assert.match(routing, /SEARCH_RPC_BACKUP_URL/);
assert.match(routing, /EXECUTION_RPC_BACKUP_URL/);
assert.match(routing, /MONITOR_RPC_BACKUP_URL/);
assert.match(routing, /getRpcEndpoints\(role/);
const paper = fs.readFileSync('src/services/PaperTradeExecutor.ts','utf8');
assert.match(paper, /getPrimaryRpc\('search'\)/);
const wallet = fs.readFileSync('src/services/WalletBalanceService.ts','utf8');
assert.match(wallet, /getPrimaryRpc\('monitor'\)/);
console.log('RPC routing regression checks passed');
